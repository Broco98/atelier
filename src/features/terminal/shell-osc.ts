import { agentMarkOf } from "@/components/ui/agent-mark";
import { firstLine } from "./agents/payload";
import type { AgentSignal } from "./agents/types";

// 훅을 **안 깐** 셸에도 길을 하나 내는 자리(결정 11의 P · 구현 스펙 3절). 셸이 PTY에 찍는
// OSC 9·777과 벨을 정규 이벤트로 접는다.
//
// **보너스 길이다 — 훅이 권위다.** 여기서 나온 신호도 `applySignal`이라는 같은 문으로만
// 들어가고, 훅이 한 번이라도 말한 셸에서는 그 문이 닫힌다(`applySignal` 머리말의 권위 규칙).
// 그래서 이 파일은 「무엇이 되는가」를 **정하지 않는다** — 정규 이벤트 하나를 낼 뿐이고,
// 그것이 화면값이 되는 규칙은 `shell-attention.ts` 하나가 안다.
//
// **에이전트 어댑터와 갈라 둔 이유**는 재료다. `agents/`의 어댑터들은 「누가 무슨 훅을
// 보냈나」를 알고 그 페이로드의 키를 읽는데, 이 길에는 에이전트도 페이로드도 없다 —
// 있는 것은 본문 문자열 하나와 「그 셸에서 무엇이 도는가」뿐이다. 한 파일에 두면 「모르는
// 에이전트는 아무것도 아니다」라는 저쪽 계약이 이쪽에서 깨진다.
//
// **벨이 여기 함께 사는 것**은 같은 문·같은 권위·같은 「훅 없는 셸에서만」이기 때문이다.
// 재료가 OSC 본문이냐 도는 명령 이름이냐만 다르다.

/**
 * 승인 대기를 뜻하는 접두사 넷. **Codex TUI가 OSC 9로 보내는 문구 그대로다**(구현 스펙 3절
 * — 「Codex TUI의 OSC 9는 본문으로만 갈린다」).
 *
 * **한 글자도 접거나 넓히지 않는다.** 소문자로 접거나 부분 일치로 넓히면 「승인 요청」이라는
 * 말이 본문 가운데 들어 있는 완료 알림까지 앰버가 되고, 그 오분류는 사람이 답할 것이 없는
 * 행을 영영 세운다. 반대로 한 글자가 틀리면 진짜 승인 요청이 초록으로 뜬다 — 어느 쪽이든
 * 화면에서는 티가 안 나므로 표를 아는 자리를 여기 하나로 둔다.
 */
const WAITING_PREFIXES = [
  "Approval requested: ",
  "Codex wants to edit ",
  "Approval requested by ",
  "Plan mode prompt: ",
] as const;

/**
 * OSC 9·777의 **본문 하나**를 정규 이벤트로 접는다. 9와 777이 같은 함수를 타는 것은 구현
 * 스펙이 둘을 한 줄로 묶었기 때문이다(「그 밖의 OSC 9·777은 전부 `done`」) — 갈라 두면
 * 같은 판정이 두 벌이 된다.
 *
 * **접두사가 없으면 `end`(→ 초록)다**(결정 13의 둘째). 「모르면 무시」는 기각됐다 — 훅을 안
 * 깐 Codex 사용자가 턴 완료를 영영 못 받는다. 대신 상태는 「확인할 것」이라는 **약한 주장만**
 * 하고, 무슨 일인지는 **본문을 그대로 실어** 사람이 눈으로 읽게 한다. 그래서 결정 3의
 * 「모르면서 아는 척하지 않는다」가 지켜진다.
 *
 * **빈 본문은 아무 주장도 아니다.** 여기서 `end`를 만들면 본문 없는 OSC 한 장에 초록이 서고,
 * 그 행은 눌러 봐야 보여 줄 말이 없다.
 *
 * **777의 본문도 손대지 않고 그대로 읽는다.** 그 규약의 통상적인 모양은 `notify;<제목>;<본문>`
 * 이라 앞의 `notify;`가 화면 글자에 그대로 섞일 수 있는데, 스펙이 9와 777을 한 줄로 묶으며
 * 「본문 전체를 첫 줄로 잘라」라고만 적었다 — 여기서 규약을 하나 더 아는 척하면 스펙이 안 정한
 * 규칙이 코드에만 생긴다. 실물에서 그 글자가 보이면 그때 스펙이 정하고 이 함수가 따른다.
 *
 * 자르는 것은 훅 길과 **같은 `firstLine`**이다 — 둘째 줄·띠·알림이 다 한 줄이라 자르는 자리가
 * 하나여야 하고, 길이로 안 자르는 것도 그쪽 계약 그대로다(넘치는 것은 화면이 페이드로 끝낸다).
 */
export function oscSignal(body: string): AgentSignal | null {
  // **접두사는 자르기 전 본문의 맨 앞에서 잰다.** `firstLine`을 먼저 태우면 그것이 양끝을
  // 다듬어서 접두사의 **끝 공백이 사라지고**, 뒤가 빈 `Approval requested: ` 한 장이 앰버가
  // 아니라 초록으로 뜬다 — 사람이 답할 것이 있는 순간에 답할 것이 없다고 말하는 셈이다.
  // 스펙의 말도 「…로 시작하면」이라 재는 자리가 본문의 맨 앞이 맞다.
  const prefix = WAITING_PREFIXES.find((one) => body.startsWith(one));
  // 접두사만 오고 뒤가 비면 말은 없되 앰버는 선다. `null`은 「지운다」가 아니라 「직전 것을
  // 그대로 둔다」이고, 그 규칙은 `applySignal`이 든다.
  if (prefix !== undefined) return { event: "waiting", message: firstLine(body.slice(prefix.length)) };

  const line = firstLine(body);
  return line === null ? null : { event: "end", message: line };
}

/**
 * 벨(`onBell`) 한 번을 정규 이벤트로 접는다. 재료는 **그 셸에서 지금 도는 것의 원문**이다.
 *
 * **아는 에이전트가 돌면 무시한다**(스펙 전이 표의 벨 두 줄). claude·codex가 스스로 울리는
 * 벨은 훅이 이미 같은 말을 한 것이라, 안 무시하면 초록이 하나 더 서서 훅이 방금 세운 앰버를
 * 덮는다. 남는 것은 「모르는 명령이 끝나며 울린 벨」 하나이고, 그것이 이 판이 판 04 결정 21의
 * 감수를 절반 닫는 자리다 — `; tput bel`을 붙인 사람은 밀려난 칸에서도 띠가 받는다.
 *
 * **표를 다시 적지 않는다.** 「아는 에이전트」를 아는 자리는 `agentMarkOf` 하나다(판 04
 * 결정 15) — 여기 이름 목록을 따로 두면 마크가 뜨는 셸과 벨이 무시되는 셸이 갈리고, 그
 * 어긋남은 화면에서 아무 표시도 안 난다.
 *
 * **판정 시점은 벨이 울린 순간의 `pty:running` 값이다**(구현 결정 1). 그 값은 1초 폴링이라
 * 경계에서 어긋날 수 있고, 어긋나면 **초록이 하나 더 뜨는 쪽으로** 틀린다 — 스펙이 그 방향을
 * 택했다. 반대로 틀리면 사람이 부른 것을 앱이 삼킨다.
 *
 * **말은 안 싣는다.** 벨은 소리 한 번이라 말할 것이 없고, `null`은 「지운다」가 아니라
 * 「직전 것을 그대로 둔다」다(`applySignal`).
 */
export function bellSignal(running: string | null): AgentSignal | null {
  return agentMarkOf(running) === null ? { event: "end", message: null } : null;
}
