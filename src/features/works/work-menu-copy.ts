import type { Mode } from "@/mode";

/**
 * ⋯ 메뉴의 두 확인 대화가 하는 말 — **무엇이 남고 무엇이 사라지는가**.
 *
 * 문구는 실제로 남는 것과 사라지는 것을 **둘 다** 말한다. 아카이빙 쪽만 「보존」을 말하면
 * 대비로 인해 삭제가 커밋까지 지우는 것처럼 읽히고(브랜치는 양쪽 다 남는다), 워크트리
 * 제거가 gitignore된 파일(.env·로컬 DB·빌드 산출물)까지 가져간다는 사실은 **양쪽 다** 적는다.
 * 그 파일들은 dirty 검사에 잡히지 않으므로 이 문구가 유일한 경고이고, 둘 다 같은
 * worktree_remove를 탄다 — 삭제 쪽은 스펙까지 지우니 더 잃는다.
 *
 * **세계마다 낱말이 다르다**(결정 17 · #186). Room에는 워크트리도 브랜치도 커밋도 없는데
 * Atelier 문구를 그대로 띄우면, 사용자는 지우기 직전의 그 창에서 「Room에도 워크트리와
 * 브랜치가 있다」를 배운다 — `archive-copy.ts`가 빈 화면에서 「워크트리는 정리되고」를 뺀
 * 이유와 같고, 그 문장이 실제로 사람을 만나는 자리는 아무도 안 여는 빈 화면이 아니라
 * 여기다. 스펙의 「⋯ 메뉴에는 프로젝트 동작이 원래 없다」는 **동작**을 말한 것이라 이
 * 어휘 구멍을 안 덮는다.
 *
 * 코어가 프로젝트 0개 Work에서 실제로 하는 일이 이 문구의 근거다(works.rs): 아카이빙은
 * 폴더를 아카이브로 옮기고 기록을 쓸 뿐이고(지울 워크트리가 없다), 삭제는 그 폴더를
 * 통째로 지운다. 그래서 Maison 벌에는 「git이 무시하는 파일」 경고도 없다 — 그 경고는
 * 워크트리 폴더에 딸린 말이다.
 *
 * `satisfies Record<Mode, …>`가 그물이다: 세계를 하나 빠뜨리면 그 자리에서 L0가 빨개진다.
 * Atelier 문구는 **한 글자도 안 바뀐 채** 옮겨 왔다.
 */
const COPY = {
  atelier: {
    archive:
      "스펙과 기록은 남고 워크트리 폴더가 정리돼요. 브랜치와 커밋은 그대로예요.\n" +
      "다만 git이 무시하는 파일(.env, 로컬 DB, 빌드 산출물)은 폴더와 함께 사라져요.\n" +
      "되돌릴 수 없어요.",
    remove:
      "워크트리 폴더와 스펙 문서가 모두 지워져요. 브랜치와 커밋은 남지만 기록은 안 남아요 —\n" +
      "남길 것이 있다면 아카이빙을 쓰세요.\n" +
      "git이 무시하는 파일(.env, 로컬 DB, 빌드 산출물)도 폴더와 함께 사라져요.\n" +
      "되돌릴 수 없어요.",
  },
  maison: {
    archive: "스펙과 기록이 아카이브로 옮겨져요.\n되돌릴 수 없어요.",
    remove:
      "Room 폴더와 스펙 문서가 모두 지워져요. 기록은 안 남아요 —\n" +
      "남길 것이 있다면 아카이빙을 쓰세요.\n" +
      "되돌릴 수 없어요.",
  },
} as const satisfies Record<Mode, { archive: string; remove: string }>;

/** 아카이빙 확인 대화의 본문. */
export function archiveConfirmBody(mode: Mode): string {
  return COPY[mode].archive;
}

/** 삭제 확인 대화의 본문. */
export function removeConfirmBody(mode: Mode): string {
  return COPY[mode].remove;
}
