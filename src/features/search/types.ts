/**
 * 팔레트가 그리는 한 줄. **코어가 정하는 모양 그대로다** — 순위도 층 규칙도 코어에 있고
 * (결정 15), 프런트는 받은 것을 순서대로 그린다.
 *
 * **갈래를 태그로 가른다.** 필드 유무로 종류를 되짚으면 갈래가 늘 때마다 되짚는 규칙이
 * 늘고, 그 규칙은 어긋나도 화면에 티가 안 난다. 다섯이 한 목록에 서고 줄마다 다른 것을 그린다.
 *
 * **셸은 여기 없고**(결정 2) **실행되는 것도 없다**(결정 1) — 다섯이 전부 「가는 곳」이라
 * Enter가 언제나 한 가지 뜻이다.
 */
export type SearchHit =
  | {
      kind: "destination";
      /**
       * **`key`뿐이다**(결정 21). 라벨과 라우트는 프런트에만 산다(`destinations.ts`) —
       * 코어에 건넨 말을 코어가 되돌려 보내면 정본이 둘이 되고, 어긋나는 날 어느 쪽이
       * 맞는지 아무도 모른다.
       */
      key: string;
    }
  | {
      kind: "work";
      slug: string;
      title: string;
      /** 아카이브 work은 **가는 화면이 다르다** — 고르기 전에 그것을 알아야 한다. */
      archived: boolean;
    }
  | { kind: "project"; slug: string; name: string }
  | {
      kind: "doc";
      slug: string;
      /** **work 제목이다.** `overview.md`가 29개라 파일명만으로는 어느 것인지 못 고른다. */
      title: string;
      /**
       * **가는 주소의 `file` 값**이다(결정 28) — 파일 시스템 경로가 아니다. 활성 문서는 spec
       * 루트 기준이고 아카이브 문서는 work 루트 기준인데, 그 둘은 각 화면이 `?file=`을 읽는
       * 방식 그대로다. 어느 화면인지는 `archived`가 말한다.
       */
      path: string;
      archived: boolean;
    }
  | {
      kind: "text";
      slug: string;
      /** 문서 줄과 같다 — **work 제목이다.** */
      title: string;
      /** 문서 줄과 같다 — **가는 주소의 `file` 값**이다(결정 28). 가는 곳도 문서 줄과 같다. */
      path: string;
      archived: boolean;
      /**
       * **맞은 문단을 한 줄로 편 것.** 열기 전에 왜 떴는지를 말하는 자리이고, 그래서 갈래가
       * 갈린다 — 이름으로 맞은 문서 줄에는 말할 것이 없다.
       *
       * **프리뷰 패널이 없는 이유가 이 값이다**(결정 6). 노션의 오른쪽 프리뷰는 제목을 찾는
       * 검색이라 「이 페이지가 맞나」를 답해야 해서 있는 것인데, 여기는 본문 전문검색이라
       * **매치된 줄 자체가 그 답**이다.
       *
       * **`heading`은 아직 없다**(결정 31) — 판 03이 그때 더한다.
       */
      snippet: string;
    };

/**
 * 코어에 건네는 **「무엇이 있는가」**(결정 21). main nav의 라우트 문자열은 프런트 것이고
 * 코어가 알면 목적지가 늘 때마다 Rust를 고쳐야 한다 — `nav-items.ts`가 「앞으로 늘어날
 * 목적지는 이 배열에 한 줄」이라고 못 박아 둔 것이 깨진다. 그렇다고 프런트가 그 층만 직접
 * 맞추면 AND·대소문자 규칙과 층 순서가 두 곳으로 갈린다.
 *
 * **맞추는 재료는 라벨이다** — 화면에 적히는 것이 그것이라 왜 떴는지가 줄 안에서 설명된다.
 */
export type Destination = { key: string; label: string };

/**
 * 한 질의의 답 전부. **「잘렸다」가 줄이 아니라 목록의 성질인 것**이 이 모양의 전부다 —
 * 딱 20줄이 온 것과 21번째부터 잘린 것이 줄들로는 같아서, 화면이 그것을 가르려면 상한을
 * 자기도 알고 세어야 한다. 그러면 상한이 두 자리에 살고 어긋나도 티가 안 난다(결정 15).
 *
 * **층마다 갈리지 않는다** — 상한은 층마다지만(결정 24) 화면이 하는 말은 「일부만 보입니다」
 * 하나이고, 그 말은 어느 층이 걸렸든 똑같이 참이다.
 */
export type SearchResults = {
  hits: SearchHit[];
};
