/**
 * 팔레트가 그리는 한 줄. **코어가 정하는 모양 그대로다** — 순위도 층 규칙도 코어에 있고
 * (결정 15), 프런트는 받은 것을 순서대로 그린다.
 *
 * 갈래가 지금은 문서 하나뿐이라 `kind`가 없어도 그려지지만 **태그를 지우지 않는다**:
 * 「가는 곳」·작업·프로젝트·본문이 뒤 판에서 같은 목록에 서고, 그때 줄마다 다른 것을
 * 그려야 한다. 필드 유무로 종류를 되짚는 코드가 그 자리를 대신하면 갈래가 늘 때마다
 * 되짚는 규칙이 는다.
 */
export type SearchHit = {
  kind: "doc";
  slug: string;
  /** **work 제목이다.** `overview.md`가 29개라 파일명만으로는 어느 것인지 못 고른다. */
  title: string;
  /**
   * **가는 주소의 `file` 값**이다(결정 28) — 파일 시스템 경로가 아니다. 활성 문서는 spec
   * 루트 기준이고 아카이브 문서는 work 루트 기준인데, 그 둘은 각 화면이 `?file=`을 읽는
   * 방식 그대로다. 어느 화면인지는 `archived`가 말한다.
   */
  path: string;
  archived: boolean;
};

/**
 * 한 질의의 답 전부. **「잘렸다」가 줄이 아니라 목록의 성질인 것**이 이 모양의 전부다 —
 * 딱 20줄이 온 것과 21번째부터 잘린 것이 줄들로는 같아서, 화면이 그것을 가르려면 상한을
 * 자기도 알고 세어야 한다. 그러면 상한이 두 자리에 살고 어긋나도 티가 안 난다(결정 15).
 */
export type SearchResults = {
  hits: SearchHit[];
  truncated: boolean;
};
